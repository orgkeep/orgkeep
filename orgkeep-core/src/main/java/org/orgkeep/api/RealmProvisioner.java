package org.orgkeep.api;

import org.orgkeep.api.model.CreateRealmRequest;
import org.orgkeep.api.model.CreateRealmResponse;
import org.orgkeep.api.model.DashboardClientSettings;
import org.orgkeep.api.model.SmtpSettings;

import java.util.Optional;

public interface RealmProvisioner {
    /**
     * Creates the realm with its roles, its owner and the default catalog, then {@link #ensureDefaults}.
     * Without adminPassword, the owner gets a random password and the invitation email (see {@link #configureSmtp}).
     */
    CreateRealmResponse create(CreateRealmRequest request);

    /**
     * Sets the SMTP server Keycloak uses for the emails of the realm, replacing the keys Orgkeep manages (host,
     * port, from, fromDisplayName, starttls, ssl, auth, user, password) and keeping the others (reply-to, envelope
     * from... set in the Keycloak console). Without it, users created without password receive no invitation.
     */
    void configureSmtp(String name, SmtpSettings smtp);

    /**
     * Sets the theme of the login pages of one client: they replace the theme of the realm when the login comes from
     * this client. The theme must be deployed in Keycloak: an unknown theme is not refused, Keycloak falls back to
     * its default one. Idempotent.
     *
     * @return false if the realm has no such client
     */
    boolean setLoginTheme(String name, String clientId, String theme);

    /**
     * Creates the confidential client of orgkeep-dashboard when missing, and on an existing one rewrites what Orgkeep
     * owns (flows, redirect URIs, PKCE, login theme). The secret is generated by Keycloak at creation and never changed
     * afterwards. Idempotent.
     */
    void ensureDashboardClient(String name, DashboardClientSettings settings);

    /**
     * Creates what Orgkeep expects in the realm when it is missing: the login client of the realm owner's
     * applications, whose clientId is the realm name. Not the default catalog, which the realm owner may delete.
     * Idempotent: also run at each startup on an existing realm.
     */
    void ensureDefaults(String name);

    /**
     * Makes the realm role realm-owner a composite of the client role realm-management/realm-admin: the realm owners
     * can then manage their realm in the Keycloak admin console, confined to it. For ON_PREM, where the realm owner
     * runs their own Keycloak; not in SAAS. Idempotent.
     */
    void grantConsoleAccess(String name);

    /**
     * Makes the user named by the configuration the only direct holder of the realm roles of Orgkeep (realm-owner,
     * realm-admin, realm-user): grants them what they lack, then removes these roles from every other direct holder
     * and ends their sessions. The user is found by username, or by email when there is no username. Only direct role
     * mappings are handled: a role received through a group or a composite stays. For ON_PREM, on an existing realm.
     * All the checks come before any change; idempotent.
     *
     * @throws IllegalStateException if the user is not found, is disabled, has another email than the one given (when
     *                               found by username) or is a member of an organisation
     */
    void enforceSingleOwner(String name, Optional<String> username, String email);

    void delete(String name);
    boolean exists(String name);
}
